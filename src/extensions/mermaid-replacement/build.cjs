'use strict';

const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const read = (file) => fs.readFileSync(path.join(__dirname, file), 'utf8');
const vendor = read('vendor/dist/mermaid.min.js');
const globalAssignment = 'globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;';
if (!vendor.trimEnd().endsWith(globalAssignment)) {
  throw new Error('Unsupported official browser bundle export');
}
const officialFactory = `function createOfficialMermaid() {
  const library = (function (require, module, exports) {
    ${vendor.replace(globalAssignment, '')}
    return __esbuild_esm_mermaid_nm.mermaid.default;
  })();
  library.startOnLoad = false;
  return library;
}`;
fs.writeFileSync(path.join(__dirname, 'main-world.js'),
  '// Generated by build.cjs. Official Mermaid 12.1.0; see vendor/LICENSE.\n' +
  read('hook.js').replace('/* OFFICIAL_FACTORY */', () => officialFactory));
const sources = JSON.parse(read('sources.json'));
sources.injection = 'MV3 isolated bootstrap inserts a nonce-aware page script; Rspack factory hook';
sources.vendorSha256 = crypto.createHash('sha256').update(vendor).digest('hex');
delete sources.preservedModules;
fs.writeFileSync(path.join(__dirname, 'sources.json'), JSON.stringify(sources, null, 2) + '\n');
console.log('Built main-world.js with the official standalone Mermaid bundle');
